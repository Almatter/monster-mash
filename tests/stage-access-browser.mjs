import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
import {mkdir} from 'node:fs/promises';

const {chromium}=await import(pathToFileURL(process.env.PLAYWRIGHT_PATH).href);
const browser=await chromium.launch({headless:true,executablePath:process.env.BROWSER_PATH});
await mkdir('test-results',{recursive:true});
try{
 const page=await browser.newPage({viewport:{width:1440,height:900}}),errors=[];
 page.on('pageerror',error=>errors.push(error.message));
 let officialDate='Wed, 07 Oct 2026 23:59:59 GMT';
 await page.route('**/index.html?stage-clock=*',route=>route.fulfill({status:200,headers:{Date:officialDate,'Content-Type':'text/html'},body:''}));
 await page.goto('http://127.0.0.1:4173/');
 await page.waitForSelector('#stageChoices button');
 assert.equal(await page.locator('#stageChoices button').count(),4);
 assert.match(await page.locator('#stageChoices').textContent(),/FUTURE STAGE/);
 await page.locator('[data-phase="1"]').click();
 assert.equal(await page.locator('[data-phase="1"]').getAttribute('aria-pressed'),'false');
 assert.match(await page.locator('#stageStatus').textContent(),/0 \/ 7 qualifying days/);
 await page.evaluate(async()=>{
  const {normalizeProfile,recordProgress}=await import('./src/profile.js');
  const profile=normalizeProfile(null);
  for(let day=1;day<=7;day++)recordProgress(profile,{id:'gate-'+day,monsterId:'devourer',phase:0,reason:'overwhelmed',values:{seconds:520,kills:16000},best:{seconds:520}},true,new Date(Date.UTC(2026,9,day,16)));
  localStorage.setItem('mm-profile',JSON.stringify(profile));
 });
 await page.reload();await page.waitForSelector('[data-phase="1"]');
 assert.match(await page.locator('[data-phase="1"]').textContent(),/OPENS OCTOBER 8/);
 await page.locator('[data-phase="1"]').click();
 assert.equal(await page.locator('[data-phase="1"]').getAttribute('aria-pressed'),'false');
 assert.match(await page.locator('#stageStatus').textContent(),/remains locked until October 8/);
 await page.locator('[data-phase="2"]').click();
 assert.match(await page.locator('#stageStatus').textContent(),/awaits its own title, map and release date/);
 await page.screenshot({path:'test-results/stage2-locked.png'});
 officialDate='Thu, 08 Oct 2026 04:00:00 GMT';
 await page.locator('[data-phase="1"]').click();
 await page.waitForFunction(()=>document.querySelector('[data-phase="1"]').getAttribute('aria-pressed')==='true');
 assert.match(await page.locator('#scenarioName').textContent(),/STAGE 2.*ADAPTATION/);
 await page.screenshot({path:'test-results/stage2-open-menu.png'});
 await page.evaluate(async()=>{const {Game}=await import('./src/simulation.js');const update=Game.prototype.update;Game.prototype.update=function(...args){window.testGame=this;return update.apply(this,args);};});
 await page.locator('#startForm button.primary').click();
 assert.equal(await page.evaluate(()=>testGame.phase),1);
 assert.match(await page.locator('#phaseLabel').textContent(),/ADAPTATION/);
 await page.waitForFunction(()=>performance.getEntriesByType('resource').some(item=>item.name.includes('floor-adaptation.webp')));
 await page.screenshot({path:'test-results/stage2-battle.png'});
 await page.locator('#pause').click();await page.locator('#endRun').click();
 await page.waitForFunction(()=>document.querySelector('#runCode').value.startsWith('MM4.'));
 assert.match(await page.locator('#resultContext').textContent(),/STAGE 2.*ADAPTATION/);
 assert.equal(await page.evaluate(async()=>{const {decodeRun}=await import('./src/run-code.js');return (await decodeRun(document.querySelector('#runCode').value)).phase;}),1);
 assert.deepEqual(errors,[]);
 await page.close();
 const touch=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 await touch.goto('http://127.0.0.1:4173/');await touch.waitForSelector('#stageChoices button');
 assert.equal(await touch.locator('#stageChoices button').count(),4);
 await touch.locator('[data-phase="1"]').tap();
 assert.match(await touch.locator('#stageStatus').textContent(),/0 \/ 7 qualifying days/);
 await touch.screenshot({path:'test-results/stage2-mobile-menu.png'});
 await touch.close();
 console.log('Desktop and phone: Stage 2 title/date locks, future stages, playable scenario, floor asset and run metadata pass');
}finally{await browser.close();}
